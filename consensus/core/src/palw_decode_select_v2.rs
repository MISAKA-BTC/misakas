    use super::*;
    use crate::palw_step_refute::base0_decode_token_select_v1;

    /// A cheap deterministic row generator — no dev-dependency, and the same rows on every host.
    fn rows(seed: u64, count: usize, width: usize, spread: i32) -> Vec<Vec<i32>> {
        let mut x = seed | 1;
        let mut next = move || {
            x ^= x << 13;
            x ^= x >> 7;
            x ^= x << 17;
            x
        };
        (0..count).map(|_| (0..width).map(|_| ((next() % (2 * spread as u64 + 1)) as i64 - spread as i64) as i32).collect()).collect()
    }

    /// **Z8's first half: `T_q = 0` IS the shipped rule.** Not "agrees on typical rows" — the same
    /// index on every row, including rows that are all ties, rows with `i32::MIN`/`MAX`, and rows
    /// whose argmax is the last lane. The key is `value × T_ONE`, a strictly increasing function
    /// of the value, so this is an identity rather than a coincidence; the sweep is what stops a
    /// later edit from making it one.
    #[test]
    fn the_greedy_temperature_is_the_shipped_rule_on_every_row() {
        let seed = PALW_DECODE_SEED_GREEDY;
        let hot = [7u8; 32];
        for width in [1usize, 2, 3, 17, 64, 129, 1024] {
            for spread in [1i32, 3, 1_000, i32::MAX / 2] {
                for row in rows(0x9E37_79B9_7F4A_7C15 ^ width as u64, 24, width, spread) {
                    let v1 = base0_decode_token_select_v1(&row);
                    for position in [0u32, 1, 4_095] {
                        assert_eq!(
                            decode_token_select_v2(&row, &seed, position, PALW_DECODE_TEMPERATURE_GREEDY),
                            v1,
                            "T_q = 0 must be v1 at width {width}, spread {spread}"
                        );
                        // And the SEED must be inert at T_q = 0, or "greedy" would be a draw.
                        assert_eq!(decode_token_select_v2(&row, &hot, position, PALW_DECODE_TEMPERATURE_GREEDY), v1);
                    }
                }
            }
        }
        // The degenerate rows the generator cannot produce.
        for row in [vec![i32::MIN; 5], vec![i32::MAX; 5], vec![0; 5], vec![i32::MIN, i32::MAX, i32::MIN]] {
            assert_eq!(decode_token_select_v2(&row, &seed, 0, 0), base0_decode_token_select_v1(&row));
        }
    }

    /// The table is exactly what the checked-in generator prints — length, monotonicity, the two
    /// extremes, and the keyed hash of the whole array. A table edited by hand is a consensus
    /// fork that compiles.
    #[test]
    fn the_gumbel_table_is_the_one_the_script_generates() {
        assert_eq!(PALW_GUMBEL_Q24_V1.len(), PALW_GUMBEL_TABLE_LEN);
        assert_eq!(PALW_GUMBEL_TABLE_LEN, 8_192);
        assert!(PALW_GUMBEL_Q24_V1.windows(2).all(|w| w[0] < w[1]), "the quantile is strictly increasing");
        assert_eq!(PALW_GUMBEL_Q24_V1[0], -38_126_968, "-ln(-ln(0.5/8192)) in Q24");
        assert_eq!(PALW_GUMBEL_Q24_V1[PALW_GUMBEL_TABLE_LEN - 1], 162_806_608, "-ln(-ln(8191.5/8192)) in Q24");
        let mut state = blake2b_simd::Params::new().hash_length(64).key(PALW_DECODE_SELECT_V2_GUMBEL_DOMAIN).to_state();
        for e in PALW_GUMBEL_Q24_V1.iter() {
            state.update(&e.to_le_bytes());
        }
        assert_eq!(state.finalize().to_hex().as_str(), PALW_GUMBEL_Q24_V1_DIGEST_HEX, "scripts/palw-gumbel-table.py --hash");
    }

    /// The overflow bound the key's doc comment claims, checked against the SHIPPED table rather
    /// than against a remembered range: an i64 that wrapped here would make two honest nodes
    /// select different tokens, which is the one failure a sampler must not have.
    #[test]
    fn the_keyed_row_cannot_overflow_an_i64() {
        let (lo, hi) = (PALW_GUMBEL_Q24_V1[0] as i64, PALW_GUMBEL_Q24_V1[PALW_GUMBEL_TABLE_LEN - 1] as i64);
        assert!(lo.abs().max(hi) < 1i64 << 28, "|G| < 2^28");
        let worst = (i32::MIN as i64).abs() * PALW_DECODE_T_ONE + (u32::MAX as i64) * hi;
        assert!(worst < i64::MAX / 4, "the worst key is inside i64 by a factor of four: {worst}");
        // And the real arithmetic at the extremes, unwrapped.
        for v in [i32::MIN, -1, 0, 1, i32::MAX] {
            for t in [1u32, 1 << 24, u32::MAX] {
                let k = decode_lane_key_v2(v, &[9u8; 32], 3, 11, t);
                let noise = (t as i64).checked_mul(gumbel_q24_v1(&[9u8; 32], 3, 11) as i64).unwrap() >> K;
                assert_eq!(k, (v as i64).checked_mul(PALW_DECODE_T_ONE).unwrap() + noise);
            }
        }
    }

    /// The index is a function of all three inputs and of nothing else, and it covers the table.
    /// A key that ignored the position would give one lane the same variate at every step, which
    /// is a repetition dressed as a sample.
    #[test]
    fn the_index_moves_with_the_seed_the_position_and_the_lane() {
        let a = [1u8; 32];
        let mut b = a;
        b[31] ^= 1;
        assert_ne!(gumbel_index_v1(&a, 0, 0), gumbel_index_v1(&b, 0, 0), "one bit of the seed");
        let over_positions: std::collections::BTreeSet<usize> = (0..64u32).map(|p| gumbel_index_v1(&a, p, 5)).collect();
        assert!(over_positions.len() > 50, "the position must move the draw: {} distinct of 64", over_positions.len());
        let over_lanes: std::collections::BTreeSet<usize> = (0..64usize).map(|l| gumbel_index_v1(&a, 9, l)).collect();
        assert!(over_lanes.len() > 50, "the lane must move the draw: {} distinct of 64", over_lanes.len());
        assert!((0..8_192u32).map(|p| gumbel_index_v1(&a, p, 0)).all(|i| i < PALW_GUMBEL_TABLE_LEN));
    }

    /// **The sampler samples.** At a temperature comparable to the row's own spread the selected
    /// token is not always the greedy one, and over many seeds the greedy token is still the
    /// modal outcome — the two facts that separate "a real distribution" from "noise" and from
    /// "greedy with extra steps".
    #[test]
    fn a_hot_temperature_draws_and_a_cold_one_collapses_to_greedy() {
        let row: Vec<i32> = vec![100, 98, 95, 40, 5, -20];
        let greedy = base0_decode_token_select_v1(&row);
        // A temperature of 1.0 in the class's own logit units — `1 << K` is Q24's own unit.
        let hot = 1u32 << K;
        let mut seen = std::collections::BTreeMap::<usize, u32>::new();
        for s in 0..256u32 {
            let mut seed = [0u8; 32];
            seed[..4].copy_from_slice(&s.to_le_bytes());
            *seen.entry(decode_token_select_v2(&row, &seed, 0, hot)).or_default() += 1;
        }
        assert!(seen.len() > 1, "a hot temperature that always picks one lane is not a sampler");
        let modal = seen.iter().max_by_key(|(_, n)| **n).map(|(l, _)| *l).unwrap();
        assert_eq!(modal, greedy, "the highest logit must still be the most likely draw");
        // Cold: 2^-10 of a logit unit, so the gap of 2 dominates every variate on every seed.
        let cold = 1u32 << (K - 10);
        for s in 0..64u32 {
            let mut seed = [0u8; 32];
            seed[..4].copy_from_slice(&s.to_le_bytes());
            assert_eq!(decode_token_select_v2(&row, &seed, 0, cold), greedy);
        }
    }

    /// **Z8's second half, at the arithmetic that the court's two disclosures feed.** Under a seed
    /// and `T_q > 0` the beat rule convicts the lane that is not the keyed argmax and acquits the
    /// one that is — for EVERY lane of the row, which is the sweep the refutation arm inherits.
    #[test]
    fn the_two_key_comparison_convicts_exactly_the_lanes_that_beat() {
        let seed = [0x5Au8; 32];
        let t = 1u32 << 21;
        for position in [0u32, 7] {
            for row in rows(0xDEAD_BEEF ^ position as u64, 12, 40, 500) {
                let winner = decode_token_select_v2(&row, &seed, position, t);
                let winner_key = decode_lane_key_v2(row[winner], &seed, position, winner, t);
                for (lane, v) in row.iter().enumerate() {
                    let key = decode_lane_key_v2(*v, &seed, position, lane, t);
                    assert!(!decode_lane_beats_v2(key, lane, winner_key, winner), "lane {lane} beats the argmax");
                    if lane != winner {
                        assert!(
                            decode_lane_beats_v2(winner_key, winner, key, lane),
                            "the argmax must beat every other lane — a committed {lane} is convictable"
                        );
                    }
                }
            }
        }
    }
