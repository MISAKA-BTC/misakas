//! **ADR-0082 Decision 11: the committed decode token is a SEEDED argmax, and the pin's
//! refutation is unchanged.**
//!
//! The shipped rule is `base0_decode_token_select_v1` — the argmax of the integer logits row,
//! ties to the lowest index (`palw_step_refute.rs`, ADR-0049 Decision E). It is not a sampler,
//! and the tree's own measurement of what that costs is on record at `params.rs`: a small model
//! at temperature zero "collapses to a handful of attractors (measured min-entropy ~3.1 bits over
//! 60 seeds …)". A thousand-token greedy answer is a repetition, not an artifact.
//!
//! This module is the one sampler an exact court can carry:
//!
//! ```text
//!   committed_j = argmax_j ( values[j] · T_ONE  +  T_q · G_j )      ties to the LOWEST index
//!   T_ONE       = 1 << 24                      (Q24 — `palw_base0::K`, the class's own fixed point)
//!   G_j         = PALW_GUMBEL_Q24_V1[ top 13 bits of H(seed ‖ position ‖ j) ]
//! ```
//!
//! Two properties are what make it carriable, and neither is true of the obvious alternatives:
//!
//! * **The key is a PER-LANE function.** Nothing in `decode_lane_key_v2` reads another lane, so
//!   the refutation stays the two-disclosure form of the tiled logits pin (ADR-0049 Decision E):
//!   open the committed lane's tile and a beating lane's tile, recompute two keys, compare. A
//!   softmax-normalising sampler would need the WHOLE row at every dispute, which at a Qwen-class
//!   vocabulary is the 993 KB row `palw_close_budget` already refuses.
//! * **Gumbel-max samples exactly from `softmax(logits / T)`**, so a user gets a real
//!   distribution rather than a heuristic, and the temperature means what a user thinks it means.
//!
//! **`T_q = 0` is byte-identical to `base0_decode_token_select_v1`** on every row: the Gumbel term
//! vanishes from the key, and the key becomes a strictly increasing function of the value, so the
//! argmax and the tie rule are the same ones. That is what every shipped row keeps, and
//! `the_greedy_temperature_is_the_shipped_rule_on_every_row` sweeps it over random rows.
//!
//! **No transcendental runs here.** `G` is `-ln(-ln(u))`, which a consensus rule may not evaluate;
//! the variates are enumerated once by `scripts/palw-gumbel-table.py` at a pinned resolution and
//! the runtime does one array index — the same shape `int_exp`'s table already has in the class's
//! kernel catalog. `the_gumbel_table_is_the_one_the_script_generates` pins the array's hash.
//!
//! **Where the seed comes from, and why it cannot be ground.** `(sampling_seed, temperature_q)`
//! are fields of [`crate::palw_freeprompt_v3::PalwFreePromptJobV3`], hashed by `fp_job_id_v3`
//! like every other field and therefore inside the claim id. A seed cannot be changed after the
//! fact, and grinding one costs a WHOLE INFERENCE per draw — which is ADR-0072's rule kept (one
//! inference, one ticket) rather than broken. The seed is not a lottery input: the quantum ticket
//! still consumes a beacon that postdates the claim (ADR-0044 F6).
//!
//! **What `position` means, stated once because two sides must agree.** It is the index of the
//! COMMITTED LOGITS ROW, not a cache position: row 0 is the row the LAST PREFILL position produced
//! (the one the first answer token is selected from) and row `c` is the row decode call `c`
//! produced. That is exactly `PalwTiledDecodePinV1::position` and exactly the index the tiled
//! trace root commits rows under, so the engine's decode loop and the court's refutation index
//! the same draw. An engine that passed a cache position instead would select tokens no court
//! could reproduce.
//!
//! Nothing in this module is armed by its existence. The rule that selects between v1 and v2 is
//! `Params::palw_fp_decode_rules`, `None` on every shipped preset.

use crate::palw_base0::K;

/// The domain the Gumbel index's keyed hash runs under. Its own string, never shared: a hash that
/// two rules read is a hash one of them can steer.
pub const PALW_DECODE_SELECT_V2_GUMBEL_DOMAIN: &[u8] = b"misaka-palw/decode-select-v2/gumbel/v1";

/// `2^13` entries, so the index is exactly 13 bits of the keyed hash. The resolution is a
/// consensus constant: two nodes reading different tables select different tokens.
pub const PALW_GUMBEL_TABLE_INDEX_BITS: u32 = 13;
/// Length of [`PALW_GUMBEL_Q24_V1`].
pub const PALW_GUMBEL_TABLE_LEN: usize = 1 << PALW_GUMBEL_TABLE_INDEX_BITS;

/// `1.0` in the Q24 fixed point the class computes in — [`crate::palw_base0::K`] fractional bits,
/// derived from it rather than typed beside it.
pub const PALW_DECODE_T_ONE: i64 = 1i64 << K;

/// The temperature every shipped row carries: greedy, and byte-identical to the v1 rule.
pub const PALW_DECODE_TEMPERATURE_GREEDY: u32 = 0;
/// The seed every shipped row carries. Meaningless at [`PALW_DECODE_TEMPERATURE_GREEDY`] — the
/// key never reads it — and refused as anything else while the fence is dormant.
pub const PALW_DECODE_SEED_GREEDY: [u8; 32] = [0u8; 32];

/// **The keyed hash pin of [`PALW_GUMBEL_Q24_V1`]**, hex, as
/// `scripts/palw-gumbel-table.py --hash` prints it: BLAKE2b-512 keyed with
/// [`PALW_DECODE_SELECT_V2_GUMBEL_DOMAIN`] over the 8,192 entries as little-endian `i32`.
pub const PALW_GUMBEL_Q24_V1_DIGEST_HEX: &str =
    "d2fd7a5c4f4b3a27432233f348087018cde7e1a244d1ffb8c5b700810e2719569b408a9a1383fc3c793a7f47a8aa523f2205a8dd37db1e6cb7e83ee9ae0e1def";

/// Which table entry lane `lane` of position `position` draws under `seed`.
///
/// The top [`PALW_GUMBEL_TABLE_INDEX_BITS`] bits of a keyed BLAKE2b-512 over
/// `seed ‖ position(le) ‖ lane(le)`. Every input is a fact the claim id already fixes (the seed
/// and, through the context, the position) or the lane the court is comparing, so two nodes
/// asking about the same lane get the same entry and nothing an executor does after the fact can
/// move one.
pub fn gumbel_index_v1(seed: &[u8; 32], position: u32, lane: usize) -> usize {
    let mut state = blake2b_simd::Params::new().hash_length(64).key(PALW_DECODE_SELECT_V2_GUMBEL_DOMAIN).to_state();
    state.update(seed);
    state.update(&position.to_le_bytes());
    state.update(&(lane as u64).to_le_bytes());
    let digest = state.finalize();
    let bytes = digest.as_bytes();
    let head = u16::from_be_bytes([bytes[0], bytes[1]]);
    (head >> (16 - PALW_GUMBEL_TABLE_INDEX_BITS)) as usize
}

/// The Q24 Gumbel variate lane `lane` draws — one hash and one array index, no transcendental.
pub fn gumbel_q24_v1(seed: &[u8; 32], position: u32, lane: usize) -> i32 {
    PALW_GUMBEL_Q24_V1[gumbel_index_v1(seed, position, lane)]
}

/// **One lane's key: `value · T_ONE + ((T_q · G_lane) >> K)`, in `i64` and in Q24.**
///
/// This is the whole of Decision 11's arithmetic, and it is a pure function of ONE lane — which
/// is the property the two-disclosure refutation rests on. `T_q = 0` short-circuits the hash:
/// the term is zero by construction, so a greedy row costs exactly what it costs today.
///
/// **Both factors of the noise term are Q24, so their product is Q48 and the shift is what puts
/// it back beside the logit.** Without it `T_q` would be scaled by `2^24` against a logit that is
/// not, and a "temperature of 1" would swamp every logit by six orders of magnitude — which is
/// exactly what `a_hot_temperature_draws_and_a_cold_one_collapses_to_greedy` measured before this
/// line said `>> K`. With it, `T_q = 1 << K` is a temperature of ONE in the class's own logit
/// units, which is the number a user thinks they are setting. The shift is arithmetic, so a
/// negative product floors toward `-∞`; that is a definition, not an approximation — every node
/// computes the same integer.
///
/// No overflow is reachable. `|value| ≤ 2^31` and `T_ONE = 2^24` bound the first term by `2^55`;
/// `T_q ≤ 2^32` and `|G| < 2^28` bound the product by `2^60` BEFORE the shift; `i64` holds `2^63`.
/// `the_keyed_row_cannot_overflow_an_i64` pins both bounds against the shipped table.
pub fn decode_lane_key_v2(value: i32, seed: &[u8; 32], position: u32, lane: usize, temperature_q: u32) -> i64 {
    let base = (value as i64) * PALW_DECODE_T_ONE;
    if temperature_q == PALW_DECODE_TEMPERATURE_GREEDY {
        return base;
    }
    base + (((temperature_q as i64) * (gumbel_q24_v1(seed, position, lane) as i64)) >> K)
}

/// **Does lane `beat` beat lane `committed`?** — the tie rule of
/// [`crate::palw_step_refute::base0_decode_token_select_v1`], restated over the keys: strictly
/// greater wins, and an equal key goes to the LOWER index. The court's decode-pin arm asks
/// exactly this question about the two tiles it opened, and the engine's decode loop answers it
/// implicitly by taking the argmax; one function so the two cannot drift.
pub fn decode_lane_beats_v2(beat_key: i64, beat_lane: usize, committed_key: i64, committed_lane: usize) -> bool {
    beat_key > committed_key || (beat_key == committed_key && beat_lane < committed_lane)
}

/// **A job's sampler inputs, as the court receives them.**
///
/// The pair travels together everywhere, and it is a struct rather than two arguments for one
/// reason: an arm that takes `(seed, temperature)` positionally is an arm a caller can transpose,
/// and the two have different types only by luck.
///
/// **Where the court gets it is the load-bearing question.** It must come from the CLAIM — the
/// job the executor signed, whose id contains both fields — and never from the challenger's pin:
/// a challenger who could state the temperature could state `0`, recompute the greedy argmax, and
/// convict an honestly sampled token. The refutation arms below therefore take it as a parameter
/// and the caller must bind it to the claim; see the note on
/// [`crate::palw_step_refute::check_tiled_decode_token_refutation_v2`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PalwDecodeSamplingV2 {
    pub seed: [u8; 32],
    pub temperature_q: u32,
}

impl PalwDecodeSamplingV2 {
    /// What every shipped row carries, and what a dormant fence admits: the v1 rule exactly.
    pub const GREEDY: Self = Self { seed: PALW_DECODE_SEED_GREEDY, temperature_q: PALW_DECODE_TEMPERATURE_GREEDY };

    /// True when this pair selects exactly what `base0_decode_token_select_v1` selects.
    pub const fn is_greedy(&self) -> bool {
        self.temperature_q == PALW_DECODE_TEMPERATURE_GREEDY
    }

    /// One lane's key under this pair — [`decode_lane_key_v2`] with the pair unpacked.
    pub fn lane_key(&self, value: i32, position: u32, lane: usize) -> i64 {
        decode_lane_key_v2(value, &self.seed, position, lane, self.temperature_q)
    }

    /// The selected lane of a whole row under this pair.
    pub fn select(&self, values: &[i32], position: u32) -> usize {
        decode_token_select_v2(values, &self.seed, position, self.temperature_q)
    }
}

/// **The selection rule.** `argmax_j (values[j] · T_ONE + T_q · G_j)`, ties to the lowest index.
///
/// At [`PALW_DECODE_TEMPERATURE_GREEDY`] this is
/// [`crate::palw_step_refute::base0_decode_token_select_v1`] on every row, which is what the
/// dormant fence keeps and what `the_greedy_temperature_is_the_shipped_rule_on_every_row` sweeps.
pub fn decode_token_select_v2(values: &[i32], seed: &[u8; 32], position: u32, temperature_q: u32) -> usize {
    let mut best = 0usize;
    let mut best_key = match values.first() {
        Some(v) => decode_lane_key_v2(*v, seed, position, 0, temperature_q),
        None => return 0,
    };
    for (lane, value) in values.iter().enumerate().skip(1) {
        let key = decode_lane_key_v2(*value, seed, position, lane, temperature_q);
        if decode_lane_beats_v2(key, lane, best_key, best) {
            best = lane;
            best_key = key;
        }
    }
    best
}

