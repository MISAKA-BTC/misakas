#!/usr/bin/env python3
"""Rebind the unpublished adopted G14 list to the user-selected DAA 18,400.

Historical suite files, digests, source commit and waiver kinds are unchanged.
They are historical evidence, NOT a passing run of the current 18,400 candidate.
The final candidate requires its own manifest, tests and boundary/startup checks.
This does not authorize any additional fence or broaden an old waiver.
"""
import contextlib
import io
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_t12_17000_records as historical

AT = 18_400
HISTORICAL_RUNS_DIR = historical.RUNS_DIR
REBIND_BASIS = ('Height-only rebind of the unpublished adopted G14 list: user decision 2026-10-30, DAA 18,400. '
                'Historical evidence source/digests and waiver scope are retained; not current-candidate PASS evidence.')


def main():
    old_at, old_table, old_tier = historical.AT, historical.TABLE, historical.TIER
    historical.AT = AT
    # Values that name the flag day follow the new explicit height decision.
    # Slot classes, measured/estimated policy numbers and all run IDs stay exact.
    def rebind(value):
        if isinstance(value, str):
            return value.replace('17,400', '18,400')
        if isinstance(value, tuple):
            return tuple(rebind(v) for v in value)
        if isinstance(value, list):
            return [rebind(v) for v in value]
        return value
    historical.TABLE = rebind(historical.TABLE)
    historical.TIER = rebind(historical.TIER)
    make_waiver = historical.P.make_waiver
    def bound_waiver(fence, genesis, at, slot, kind, value, reason, decided_by):
        return make_waiver(fence, genesis, at, slot, kind, value, reason + '; ' + REBIND_BASIS,
                           decided_by + '; height user 2026-10-30')
    historical.P.make_waiver = bound_waiver
    output = io.StringIO()
    try:
        with contextlib.redirect_stdout(output):
            historical.main()
    finally:
        historical.AT, historical.TABLE, historical.TIER = old_at, old_table, old_tier
        historical.P.make_waiver = make_waiver
    text = output.getvalue().replace('PALW_T12_17000_', 'PALW_T12_18400_')
    text = text.replace('`scripts/release/gen_t12_17000_records.py` (lane ACT2)', '`scripts/release/gen_t12_18400_records.py`')
    preface = ('//! DAA 18,400 height-only rebind, user 2026-10-30. Historical 17,400 records/logs remain unchanged.\n'
               '//! Historical passing suites name their original source commit; these are NOT fresh 18,400-candidate runs.\n'
               '//! Final same-candidate tests, source manifest, boundary/startup validation and deployment remain separate gates.\n')
    # Keep generated byte-array constants reproducible without requiring a Rust toolchain in Python-only gates.
    text = text.replace('pub const PALW_T12_18400_', '#[rustfmt::skip]\npub const PALW_T12_18400_')
    first, rest = text.split('\n', 1)
    sys.stdout.write(first + '\n' + preface + rest)


if __name__ == '__main__':
    main()
